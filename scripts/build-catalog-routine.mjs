// Generates public/legacy/catalog-routine.js from the single server source
// (assistant/catalog-routine.ts + assistant/resources/catalog-formulas.json).
// Run: node scripts/build-catalog-routine.mjs   (--check fails if the file is stale)
import fs from 'node:fs';import ts from 'typescript';
const root=new URL('../',import.meta.url);
const source=fs.readFileSync(new URL('assistant/catalog-routine.ts',root),'utf8');
const data=JSON.parse(fs.readFileSync(new URL('assistant/resources/catalog-formulas.json',root),'utf8'));
// The browser needs identity, role and actives; full INCI text stays on the server.
const slim={version:data.version,products:data.products.map(({inci,checked,en,...p})=>p)};
const js=ts.transpile(source,{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2019,removeComments:true}).replace(/^export /gm,'');
const out=`/* GENERATED by scripts/build-catalog-routine.mjs from assistant/catalog-routine.ts. Do not edit. */
(function(){'use strict';
const CATALOG=${JSON.stringify(slim)};
${js}
const index=new Map(CATALOG.products.map(p=>[p.id,p]));
window.BWCatalog={version:CATALOG.version,engine:CATALOG_ROUTINE_ENGINE,formula:id=>index.get(id),caption:id=>captionFor(index.get(id)),evaluate:input=>evaluateRoutine(input,CATALOG),actionLabel};
})();
`;
const target=new URL('public/legacy/catalog-routine.js',root);
if(process.argv.includes('--check')){if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==out){console.error('public/legacy/catalog-routine.js is stale; run node scripts/build-catalog-routine.mjs');process.exit(1);}console.log('catalog-routine.js up to date');}
else{fs.writeFileSync(target,out);console.log('wrote public/legacy/catalog-routine.js',out.length,'bytes');}
